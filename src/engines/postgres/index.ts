import type { ExplainEngine, ParsedPlan, QueryResultLike, ServerInfo } from "../types";
import { rollbackPolicy } from "../shared/analyzePolicy";
import { flattenGridValue, isGridValue } from "../shared/results";
import { normalizePlan, unwrapPlanJson } from "./normalize";
import { cleanPlanText, looksLikeTextPlan, parseTextPlan } from "./parseText";
import { buildExplainSql, inspectStatement, type PostgresServerInfo } from "./statement";

const PLAN_COLUMN = "query plan";

/** Finds the EXPLAIN output among the result sets the host returned. */
export function extractPlanOutput(results: QueryResultLike[]): unknown {
  for (const result of results) {
    const field = result.fields.find((f) => f.name.toLowerCase() === PLAN_COLUMN);
    if (!field || !result.rows.length) continue;
    const values = result.rows.map((row) => row[field.name] ?? (field.id ? row[field.id] : undefined));
    // JSON format returns one row; text format returns a row per line.
    return values.length === 1 ? values[0] : values.map(String).join("\n");
  }
  throw new Error("The database did not return a query plan.");
}

function looksLikeJsonPlan(text: string): boolean {
  return /^[[{]/.test(text) && text.includes('"Plan"');
}

/** "Needs PostgreSQL 13+" when the server is older than `version` (e.g. 130000). */
function needsVersion(version: number) {
  return (server: ServerInfo | undefined) =>
    server?.version !== undefined && server.version < version ? `Needs PostgreSQL ${version / 10000}+` : undefined;
}

export function parsePostgresPlan(input: unknown): ParsedPlan {
  let value = input;
  if (isGridValue(value)) value = flattenGridValue(value);

  if (typeof value === "string") {
    const text = value.trim();
    if (looksLikeJsonPlan(text) || /^[[{]/.test(text)) {
      let json: unknown;
      try {
        json = JSON.parse(text);
      } catch (e) {
        throw new Error(`The plan JSON could not be read: ${(e as Error).message}`);
      }
      return parsePostgresPlan(json);
    }
    if (!looksLikeTextPlan(text)) {
      throw new Error("This doesn't look like PostgreSQL EXPLAIN output.");
    }
    const plan = normalizePlan(parseTextPlan(text), "text");
    return { plan, raw: cleanPlanText(text).join("\n"), rawFormat: "text" };
  }

  const top = unwrapPlanJson(value);
  return { plan: normalizePlan(top, "json"), raw: JSON.stringify([top], null, 2), rawFormat: "json" };
}

export const postgres: ExplainEngine = {
  id: "postgresql",
  displayName: "PostgreSQL",
  connectionTypes: ["postgresql"],
  supportsAnalyze: true,
  docsUrl: "https://www.postgresql.org/docs/current/using-explain.html",
  pasteHint: "Paste the output of EXPLAIN (FORMAT JSON), or the text output of EXPLAIN ANALYZE from psql.",
  options: [
    {
      id: "buffers",
      label: "Buffers",
      description: "Shared, local and temporary block reads and writes for each node.",
      defaultValue: true,
      requiresAnalyze: true,
    },
    {
      id: "verbose",
      label: "Verbose",
      description: "Output columns, schema-qualified names and per-worker details.",
      defaultValue: false,
    },
    {
      id: "settings",
      label: "Settings",
      description: "Configuration parameters that differ from the defaults and affect planning.",
      defaultValue: false,
      unavailable: needsVersion(120000),
    },
    {
      id: "wal",
      label: "WAL",
      description: "Write-ahead log records and bytes generated by data-modifying statements.",
      defaultValue: false,
      requiresAnalyze: true,
      unavailable: needsVersion(130000),
    },
  ],

  async loadServerInfo(run): Promise<PostgresServerInfo> {
    // A SELECT rather than SHOW: Beekeeper Studio's read-only mode allows it.
    const results = await run(
      "SELECT current_setting('server_version_num') AS version, current_setting('standard_conforming_strings') AS scs"
    );
    const row = results[0]?.rows[0] ?? {};
    const version = Number(row["version"]);
    if (!Number.isFinite(version)) throw new Error("Unexpected server version response.");
    return {
      version,
      versionLabel: `${Math.floor(version / 10000)}.${version % 100}`,
      standardConformingStrings: row["scs"] !== "off",
    };
  },

  inspect: inspectStatement,
  analyzePolicy: rollbackPolicy,

  async explain(request, run) {
    const sql = buildExplainSql(request);
    const results = await run(sql);
    const parsed = parsePostgresPlan(extractPlanOutput(results));
    parsed.plan.query = request.statement.statement;
    return { ...parsed, sql };
  },

  canParse(input) {
    if (typeof input === "string") {
      const text = input.trim();
      return (looksLikeJsonPlan(text) && text.includes('"Node Type"')) || looksLikeTextPlan(text);
    }
    if (isGridValue(input)) return postgres.canParse(flattenGridValue(input));
    try {
      unwrapPlanJson(input);
      return true;
    } catch {
      return false;
    }
  },

  parse: parsePostgresPlan,
};
